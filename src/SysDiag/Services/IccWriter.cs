using System.Text;
using SysDiag.Models;

namespace SysDiag.Services;

/// <summary>
/// 生成一个**真正合法**的 ICC v2.2 显示器配置文件，并带上 vcgt 校准表。
///
/// 为什么要自己按字节拼：很多「导出 ICC」的工具只是把参数写进一个空壳，
/// 系统色彩管理一读就报错、或者导进来什么也没变。这里按 ICC.1:2001-04 的布局生成：
///
///   128 字节头  +  4 字节标签数  +  N×12 字节标签表  +  标签数据（每条 4 字节对齐）
///
/// 标签选择（够用，且兼容性最好）：
///
///   desc             文字描述（textDescriptionType，v2 专用；ASCII + UTF-16BE 双份）
///   cprt             版权
///   wtpt             媒体白点（D50）
///   rXYZ/gXYZ/bXYZ   sRGB 色域矩阵（已做 D50 适配）
///   rTRC/gTRC/bTRC   各通道色调曲线（curveType，count=1 时是 u8Fixed8 的 gamma）
///   vcgt             显卡查找表——**只有这个承载实际的调色效果**
///
/// 必须说清的边界：TRC 只能表达 gamma，**亮度 / 对比度 / RGB 增益全在 vcgt 里**。
/// 所以别的软件打开这个文件，看到的 gamma 是对的，但看不到完整调整；
/// 只有真正加载 vcgt 的路径（Windows 校准加载器、本程序的 ApplyLut）才有完整效果。
/// </summary>
internal static class IccWriter
{
    private const int HeaderSize = 128;

    // D50 白点（ICC 规定的 PCS 白点），s15Fixed16
    private const uint D50X = 0x0000F6D6;
    private const uint D50Y = 0x00010000;
    private const uint D50Z = 0x0000D32D;

    // sRGB 色域矩阵（D50 适配后的标准值）
    private static readonly double[] RedXyz = { 0.4360747, 0.2225045, 0.0139322 };
    private static readonly double[] GreenXyz = { 0.3850649, 0.7168786, 0.0971045 };
    private static readonly double[] BlueXyz = { 0.1430804, 0.0606169, 0.7141733 };

    /// <summary>生成 ICC 文件的完整字节。</summary>
    public static byte[] Build(string description, ManualTune tune)
    {
        tune = tune.Clamped();

        var text = string.IsNullOrWhiteSpace(description) ? "SysDiag Manual Tune" : description.Trim();
        var ramp = tune.BuildRamp();

        var tags = new List<(string Sig, byte[] Data)>
        {
            ("desc", TextDescription(text)),
            ("cprt", TextType("No copyright. Generated by SysDiag.")),
            ("wtpt", XyzTag(D50X, D50Y, D50Z)),
            ("rXYZ", XyzTag(RedXyz)),
            ("gXYZ", XyzTag(GreenXyz)),
            ("bXYZ", XyzTag(BlueXyz)),
            ("rTRC", CurveTag(tune.Gamma)),
            ("gTRC", CurveTag(tune.Gamma)),
            ("bTRC", CurveTag(tune.Gamma)),
            ("vcgt", VcgtTag(ramp))
        };

        // 布局：头 → 标签表 → 数据区（每条 4 字节对齐）
        var tableEnd = HeaderSize + 4 + tags.Count * 12;
        var cursor = Align4(tableEnd);

        var offsets = new int[tags.Count];

        for (var i = 0; i < tags.Count; i++)
        {
            offsets[i] = cursor;
            cursor = Align4(cursor + tags[i].Data.Length);
        }

        var buffer = new byte[cursor];

        // ---------------- 头 ----------------
        WriteBe32(buffer, 0, (uint)buffer.Length);      // profile size

        buffer[8] = 2;                                   // version 2.2
        buffer[9] = 0x20;

        WriteAscii(buffer, 12, "mntr");                  // device class：显示器
        WriteAscii(buffer, 16, "RGB ");                  // data color space
        WriteAscii(buffer, 20, "XYZ ");                  // PCS
        WriteAscii(buffer, 36, "acsp");                  // 文件签名（必须有）

        var now = DateTime.Now;
        WriteBe16(buffer, 24, now.Year);
        WriteBe16(buffer, 26, now.Month);
        WriteBe16(buffer, 28, now.Day);
        WriteBe16(buffer, 30, now.Hour);
        WriteBe16(buffer, 32, now.Minute);
        WriteBe16(buffer, 34, now.Second);

        WriteBe32(buffer, 64, 0);                        // rendering intent：感知
        WriteBe32(buffer, 68, D50X);                     // illuminant（D50）
        WriteBe32(buffer, 72, D50Y);
        WriteBe32(buffer, 76, D50Z);

        // ---------------- 标签表 ----------------
        WriteBe32(buffer, HeaderSize, (uint)tags.Count);

        for (var i = 0; i < tags.Count; i++)
        {
            var at = HeaderSize + 4 + i * 12;

            WriteAscii(buffer, at, tags[i].Sig);
            WriteBe32(buffer, at + 4, (uint)offsets[i]);
            WriteBe32(buffer, at + 8, (uint)tags[i].Data.Length);

            tags[i].Data.CopyTo(buffer, offsets[i]);
        }

        return buffer;
    }

    // ---------------------------------------------------------------- 标签

    /// <summary>
    /// textDescriptionType（v2 专用）。ASCII 段给兼容性，UTF-16BE 段给中文。
    /// 布局：sig(4) 0(4) asciiCount(4) ascii(含结尾0) langCode(4) uniCount(4) uni(含结尾0)
    ///       scriptCode(2) scriptCount(1) script(67)
    /// </summary>
    private static byte[] TextDescription(string text)
    {
        var ascii = Encoding.ASCII.GetBytes(Sanitize(text));
        var hasUnicode = text.Any(c => c > 127);
        var unicode = hasUnicode ? text : "";

        var asciiCount = ascii.Length + 1;
        var unicodeCount = hasUnicode ? unicode.Length + 1 : 0;

        var size = 12 + asciiCount + 4 + 4 + unicodeCount * 2 + 2 + 1 + 67;
        var data = new byte[size];

        WriteAscii(data, 0, "desc");
        WriteBe32(data, 8, (uint)asciiCount);

        ascii.CopyTo(data, 12);
        // 结尾的 0 已经是默认值

        var p = 12 + asciiCount;

        WriteBe32(data, p, 0);                  // unicode language code：未指定
        WriteBe32(data, p + 4, (uint)unicodeCount);
        p += 8;

        if (hasUnicode)
        {
            foreach (var ch in unicode)
            {
                WriteBe16(data, p, ch);
                p += 2;
            }

            p += 2;     // 结尾 0
        }

        // scriptCode / scriptCount / script 全部留 0（默认值）
        return data;
    }

    private static byte[] TextType(string text)
    {
        var ascii = Encoding.ASCII.GetBytes(Sanitize(text));

        var data = new byte[8 + ascii.Length + 1];
        WriteAscii(data, 0, "text");
        ascii.CopyTo(data, 8);

        return data;
    }

    private static byte[] XyzTag(uint x, uint y, uint z)
    {
        var data = new byte[20];

        WriteAscii(data, 0, "XYZ ");
        WriteBe32(data, 8, x);
        WriteBe32(data, 12, y);
        WriteBe32(data, 16, z);

        return data;
    }

    private static byte[] XyzTag(double[] xyz) => XyzTag(
        S15Fixed16(xyz[0]), S15Fixed16(xyz[1]), S15Fixed16(xyz[2]));

    /// <summary>curveType：count=1 时唯一那项是 u8Fixed8 的 gamma。</summary>
    private static byte[] CurveTag(double gamma)
    {
        var value = (ushort)Math.Clamp(Math.Round(gamma * 256.0), 1, 65535);

        var data = new byte[14];
        WriteAscii(data, 0, "curv");
        WriteBe32(data, 8, 1);
        WriteBe16(data, 12, value);

        return data;
    }

    /// <summary>vcgt 表格型：3 通道 × 256 项 × 2 字节，逐通道分块，大端。</summary>
    private static byte[] VcgtTag(ushort[] ramp)
    {
        const int count = 256;

        if (ramp is not { Length: 768 }) throw new ArgumentException("LUT 必须是 768 项。", nameof(ramp));

        var data = new byte[18 + 3 * count * 2];

        WriteAscii(data, 0, "vcgt");
        WriteBe32(data, 8, 0);          // type 0 = 表格
        WriteBe16(data, 12, 3);         // 通道数
        WriteBe16(data, 14, count);
        WriteBe16(data, 16, 2);         // 每项字节数

        var p = 18;

        for (var channel = 0; channel < 3; channel++)
        {
            for (var i = 0; i < count; i++)
            {
                WriteBe16(data, p, ramp[channel * 256 + i]);
                p += 2;
            }
        }

        return data;
    }

    // ---------------------------------------------------------------- 工具

    /// <summary>ASCII 段只能放 0x20~0x7E，中文换成 '_' 避免变成问号。</summary>
    private static string Sanitize(string text)
    {
        var chars = text.Select(c => c >= 0x20 && c <= 0x7E ? c : '_').ToArray();
        var result = new string(chars);

        return result.Length > 100 ? result[..100] : result;
    }

    private static int Align4(int value) => (value + 3) & ~3;

    private static uint S15Fixed16(double value) => (uint)(int)Math.Round(value * 65536.0);

    private static void WriteAscii(byte[] buffer, int offset, string value)
    {
        if (value.Length != 4) throw new ArgumentException("签名必须是 4 个字符：" + value);

        Encoding.ASCII.GetBytes(value).CopyTo(buffer, offset);
    }

    private static void WriteBe16(byte[] buffer, int offset, int value)
    {
        buffer[offset] = (byte)(value >> 8);
        buffer[offset + 1] = (byte)value;
    }

    private static void WriteBe32(byte[] buffer, int offset, uint value)
    {
        buffer[offset] = (byte)(value >> 24);
        buffer[offset + 1] = (byte)(value >> 16);
        buffer[offset + 2] = (byte)(value >> 8);
        buffer[offset + 3] = (byte)value;
    }
}
